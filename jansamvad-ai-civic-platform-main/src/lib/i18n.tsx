export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(detectLang);

  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    try { localStorage.setItem(LANG_KEY, l); } catch { /* ignore */ }
  }, []);

  const t = useCallback((key: string, vars?: Record<string, string | number>): string => {
    const dict = translations[lang] || translations.en;
    let str = dict[key] ?? translations.en[key] ?? key;
    if (vars) {
      for (const [k, v] of Object.entries(vars)) {
        str = str.replace(new RegExp(`\\{${k}\\}`, 'g'), String(v));
      }
    }
    return str;
  }, [lang]);

  return (
    <I18nContext.Provider value={{ lang, setLang, t }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n(): I18nContextValue {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error('useI18n must be used within I18nProvider');
  return ctx;
}

export function detectTextLang(text: string): Lang {
  const mrRanges = /[\u0900-\u097F]/;
  if (mrRanges.test(text)) {
    // Both Marathi and Hindi use Devanagari. We can't perfectly distinguish,
    // but we use the app's currently selected language as a tiebreaker
    // for Devanagari text. If the app is in Marathi, treat as Marathi.
    // Otherwise default to Hindi for Devanagari.
    try {
      const saved = localStorage.getItem(LANG_KEY);
      if (saved === 'mr') return 'mr';
      if (saved === 'hi') return 'hi';
    } catch { /* ignore */ }
    return 'hi';
  }
  return 'en';
}
